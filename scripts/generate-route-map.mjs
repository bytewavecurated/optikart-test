#!/usr/bin/env node
/**
 * Generate the authoritative route map for SYSTEM.md - by importing every
 * mounted router and reading its stack, not by grepping source. A route table
 * hand-maintained next to Express is a table of last year's routes; this one
 * is the live server's own view, including the middleware names in order
 * (which is where an accidentally-unauthenticated door becomes visible).
 *
 *   node scripts/generate-route-map.mjs            # markdown to stdout
 *   node scripts/generate-route-map.mjs --check    # exit 1 if SYSTEM.md drifted
 *
 * server.js is parsed (not run) for the `app.use('/api/x', router)` lines plus
 * the handful of routes declared directly on `app`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const serverSrc = fs.readFileSync(path.join(ROOT, 'server/server.js'), 'utf8');

// 1) mounts: app.use('/api/anything', someRoutesVariable)
const useRe = /app\.use\(\s*'(\/api[^']*)'\s*,\s*([A-Za-z0-9_]+)\s*\)/g;
const varsFromImports = {};
for (const m of serverSrc.matchAll(/import\s+([A-Za-z0-9_]+)\s+from\s+'\.\/(routes\/[^']+)'/g)) {
  varsFromImports[m[1]] = m[2];
}
const mounts = [];
for (const m of serverSrc.matchAll(useRe)) {
  const file = varsFromImports[m[2]];
  if (file) mounts.push({ prefix: m[1], file });
}

// 2) direct app routes
const direct = [];
for (const m of serverSrc.matchAll(/app\.(get|post|put|patch|delete)\(\s*'([^']+)'/g)) {
  direct.push(`${m[1].toUpperCase()} ${m[2]}`);
}

// 3) import each router module and enumerate its stack
const describe = async () => {
  process.env.NODE_ENV = process.env.NODE_ENV || 'development';
  process.env.JWT_SECRET = process.env.JWT_SECRET || 'route-map-generator-not-a-real-secret-0123456789';
  process.env.MONGODB_URI = process.env.MONGODB_URI || 'mongodb://127.0.0.1:27017/routemap-nolisten';
  const lines = [];
  for (const { prefix, file } of mounts) {
    const mod = await import('../server/' + (file.endsWith('.js') ? file : file + '.js'));
    let router = mod.default ?? mod;
    // some modules export { register } - unwrap the common shapes
    const stack =
      router.stack || (router.router && router.router.stack) || (typeof router.register === 'function' ? null : null);
    lines.push('\n### `' + prefix + '`  —  server/' + (file.endsWith('.js') ? file : file + '.js'));
    if (!stack) {
      lines.push(
        '_(delegated registrar module - see the file for the full list; the router-mounts audit verifies every verb is served)_'
      );
      continue;
    }
    for (const layer of stack) {
      if (!layer.route) continue;
      const verbs = Object.keys(layer.route.methods)
        .map((v) => v.toUpperCase())
        .join('|');
      const chain = layer.route.stack
        .slice(0, -1)
        .map((h) => h.name || (h.handle && h.handle.name) || 'inline-guard')
        .filter((n, i, a) => a.indexOf(n) === i)
        .join(', ');
      lines.push('| `' + verbs + ' ' + prefix + layer.route.path + '` | ' + (chain || 'public') + ' |');
    }
  }
  return { lines, mounts, direct };
};

const report = await describe();
const lines = report.lines;

const md = [
  '<!-- generated by scripts/generate-route-map.mjs - do not hand-edit this table; regenerate. -->',
  `<!-- generated mounts: ${report.mounts.length}; direct app routes: ${report.direct.length} -->`,
  ...lines,
  '',
  '### Direct on app (from server.js)',
  ...report.direct.map((d) => '- `' + d + '`'),
].join('\n');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(path.join(ROOT, 'SYSTEM.md'))
    ? fs.readFileSync(path.join(ROOT, 'SYSTEM.md'), 'utf8')
    : '';
  // Whitespace-normalised on both sides: the markdown table lives in a
  // prettier-formatted document and prettier pads table cells - comparing
  // raw lines would report pure alignment as drift.
  const norm = (l) => l.replace(/\s+/g, ' ').trim();
  const generatedLines = md
    .split('\n')
    .filter((l) => l.startsWith('| `') || l.startsWith('### ') || l.startsWith('- `'))
    .map(norm);
  const docLines = new Set(
    current
      .split('\n')
      .filter((l) => l.startsWith('| `') || l.startsWith('### ') || l.startsWith('- `'))
      .map(norm)
  );
  const ok = generatedLines.every((l) => docLines.has(l));
  console.log(
    ok
      ? 'route map is current'
      : `DRIFT: ${generatedLines.filter((l) => !docLines.has(l)).length} route line(s) differ - regenerate and paste into SYSTEM.md`
  );
  process.exitCode = ok ? 0 : 1;
} else {
  console.log(md);
}
